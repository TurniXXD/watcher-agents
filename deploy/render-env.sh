  DISCOVERY_MIN_DOLLAR_VOLUME "${DISCOVERY_MIN_DOLLAR_VOLUME:-1000000}" \
  DISCOVERY_MAX_CANDIDATES "${DISCOVERY_MAX_CANDIDATES:-10}" \
