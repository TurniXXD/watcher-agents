  VOLATILITY_EXPANSION_THRESHOLD "${VOLATILITY_EXPANSION_THRESHOLD:-2}" \
  MARKET_BASELINE_MIN_SNAPSHOTS "${MARKET_BASELINE_MIN_SNAPSHOTS:-5}" \
  OPTIONS_VOLUME_OI_ANOMALY_THRESHOLD "${OPTIONS_VOLUME_OI_ANOMALY_THRESHOLD:-2}" \
  OPTIONS_VOLUME_BASELINE_MULTIPLIER "${OPTIONS_VOLUME_BASELINE_MULTIPLIER:-3}" \
  OPTIONS_BASELINE_MIN_SNAPSHOTS "${OPTIONS_BASELINE_MIN_SNAPSHOTS:-3}" \
  INSTITUTIONAL_CHANGE_THRESHOLD_PERCENT "${INSTITUTIONAL_CHANGE_THRESHOLD_PERCENT:-5}" \
  SHORT_INTEREST_CHANGE_THRESHOLD_PERCENT "${SHORT_INTEREST_CHANGE_THRESHOLD_PERCENT:-10}" \
  SHORT_INTEREST_DAYS_TO_COVER_THRESHOLD "${SHORT_INTEREST_DAYS_TO_COVER_THRESHOLD:-5}" \
  DISCOVERY_MARKET_DATA_ENTITLEMENT "${DISCOVERY_MARKET_DATA_ENTITLEMENT:-EOD}" \
  DISCOVERY_SCAN_INTERVAL_MINUTES "${DISCOVERY_SCAN_INTERVAL_MINUTES:-1440}" \
