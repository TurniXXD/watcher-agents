required() {
  local name="$1"

  if [[ -z "${!name:-}" ]]; then
    echo "Missing required deployment value: $name" >&2
    exit 1
  fi
}

url_safe_password() {
  local name="$1"
  local value="${!name:-}"
  if [[ -n "$value" && ! "$value" =~ ^[A-Za-z0-9_-]+$ ]]; then
    echo "$name must contain only URL-safe letters, numbers, '_' or '-'" >&2
    exit 1
  fi
}

https_origin() {
  local name="$1"
  local value="${!name:-}"
  if [[ ! "$value" =~ ^https://[A-Za-z0-9.-]+(:[0-9]+)?$ ]]; then
    echo "$name must be an HTTPS origin without a path, query, fragment, or trailing slash" >&2
    exit 1
  fi
}

write_env() {
  local path="$1"
  shift
  : >"$path"

  while (($#)); do
    local key="$1"
    local value="$2"
    local escaped

    if [[ "$value" == *$'\n'* || "$value" == *$'\r'* ]]; then
      echo "$key must be a single-line value" >&2
      exit 1
    fi

    escaped="${value//\\/\\\\}"
    escaped="${escaped//\'/\\\'}"
    printf "%s='%s'\n" "$key" "$escaped" >>"$path"
    shift 2
  done
}

