  DISCOVERY_EXCLUDE_OTC "${DISCOVERY_EXCLUDE_OTC:-true}" \
  DISCOVERY_INVESTIGATION_MINUTES "${DISCOVERY_INVESTIGATION_MINUTES:-90}" \
