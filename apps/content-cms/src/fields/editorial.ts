import type { Field, SelectField } from 'payload';
import { staffField } from '../access/roles';

export const reviewStatuses = [
  'ingested',
  'needs_review',
  'approved',
  'rejected',
  'archived',
] as const;
export type ReviewStatus = (typeof reviewStatuses)[number];

const reviewStatusLabels: Record<ReviewStatus, string> = {
  ingested: 'Ingested',
  needs_review: 'Needs Review',
  approved: 'Approved',
  rejected: 'Rejected',
  archived: 'Archived',
};

export const reviewStatusField: SelectField = {
  name: 'reviewStatus',
  type: 'select',
  required: true,
  index: true,
  defaultValue: 'needs_review',
  options: reviewStatuses.map((value) => ({
    value,
    label: reviewStatusLabels[value],
  })),
  admin: {
    position: 'sidebar',
    description:
      'Editorial review is separate from publication. Only Approved content can be published; Rejected content is never public; Archived content leaves public listings.',
  },
};

