export const slugField = (description?: string): Field => ({
  name: 'slug',
  type: 'text',
  required: true,
  unique: true,
  index: true,
  validate: (value: unknown) =>
    typeof value === 'string' &&
    /^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(value) &&
    value.length <= 120
      ? true
      : 'Use lowercase letters, numbers, and single hyphens (max 120 characters).',
  admin: {
    position: 'sidebar',
    description:
      description ??
      'Stable SEO URL segment. Changing it breaks existing links.',
  },
});

export const tagsField = (width?: string): Field => ({
  name: 'tags',
  type: 'text',
  hasMany: true,
  maxRows: 30,
  ...(width ? { admin: { width } } : {}),
});

export const statusOptions = (
  values: readonly string[],
): SelectField['options'] =>
  values.map((value) => ({
    value,
    label: value
      .split('_')
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join(' '),
  }));
